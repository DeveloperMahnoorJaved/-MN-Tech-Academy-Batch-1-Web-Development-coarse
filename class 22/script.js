// ------------Adding And Removing Elements from Array----------

// -----------Method PUSH-------------
 
var fruits = ["Apple", "Banana", "Mango"];

fruits.push("Orange");

console.log(fruits);



// ------------Method POP---------------

let fruits2 = ["Apple", "Banana", "Mango"];

fruits2.pop();

console.log(fruits2);



// -----------Method UNSHIFT--------------

let fruits3 = ["Apple", "Banana", "Mango"];

fruits3.unshift("Orange");

console.log(fruits3);

// ----------------METHOD SHIFT-------------
 
let fruits4 = ["Apple", "Banana", "Mango"];

fruits4.shift();

console.log(fruits4);

// -----------------SPLICE--------------

let fruits5 = ["Apple", "Banana", "Mango"];

fruits5.splice(2, 2 , "Orange");

console.log(fruits5);

// -------------METHOD SLICE-----------------

var fruits6 =["Apple" , " Banana" , "Mango"];

var slicedFruits = fruits6.slice(1, 2);

console.log(slicedFruits);

// _____________________Method________________________
// push()	         Last me add
// pop()	       Last se remove
// unshift()	    Start me add
// shift()	      Start se remove
// splice()	   Beech me add ya remove










